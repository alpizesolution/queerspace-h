// Generates src/cosmos-tiles.css: the repeating star and dust tiles used by the animated profile backgrounds (src/cosmos.css).
// Each tile is a list of tiny radial gradients at seeded random positions, kept away from the tile edges so the tile repeats without
// cut-off dots. They are original (drawn from nothing but this script), so there is nothing to license. Run:  node scripts/gen-cosmos-tiles.mjs
import { writeFileSync } from 'node:fs';

/** A small seeded random number generator, so the output is the same every time. */
function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * One tile: `count` dots inside a `size` px square. `radius` is the dot radius range in px, `colors` the choices, and `soft` makes
 * a dot a glow (a wider, fainter gradient) instead of a crisp point.
 */
function tile({ seed, size, count, radius, colors, soft = false, margin = 8 }) {
  const r = rng(seed);
  const dots = [];
  for (let i = 0; i < count; i++) {
    const rad = radius[0] + r() * (radius[1] - radius[0]);
    const m = Math.ceil(rad) + margin;
    const x = Math.round(m + r() * (size - 2 * m));
    const y = Math.round(m + r() * (size - 2 * m));
    const color = colors[Math.floor(r() * colors.length)];
    const d = (rad * 2).toFixed(1);
    dots.push(soft
      ? `radial-gradient(${d}px ${d}px at ${x}px ${y}px, ${color} 0%, transparent 100%)`
      : `radial-gradient(${d}px ${d}px at ${x}px ${y}px, ${color} 45%, transparent 100%)`);
  }
  return dots.join(',\n    ');
}

const white = ['rgba(255,255,255,0.95)', 'rgba(220,232,255,0.9)', 'rgba(255,238,248,0.85)'];
const palette = ['rgba(232,121,249,0.9)', 'rgba(56,189,248,0.9)', 'rgba(250,204,21,0.85)', 'rgba(167,139,250,0.9)', 'rgba(255,255,255,0.9)', 'rgba(244,114,182,0.9)'];
const pinks = ['rgba(255,170,220,0.9)', 'rgba(255,255,255,0.9)', 'rgba(255,120,200,0.85)'];
const silver = ['rgba(235,238,255,0.85)', 'rgba(190,180,240,0.8)', 'rgba(255,255,255,0.8)'];

// name -> [tile size in px, definition]. Different sizes per layer keep the layers from lining up into one obvious pattern.
const tiles = {
  'stars-s': [420, { seed: 11, size: 420, count: 26, radius: [0.5, 0.9], colors: white }],
  'stars-m': [560, { seed: 23, size: 560, count: 17, radius: [0.8, 1.3], colors: white }],
  'stars-l': [760, { seed: 37, size: 760, count: 8, radius: [1.4, 2.2], colors: white, soft: true }],
  'stars-blue': [610, { seed: 41, size: 610, count: 14, radius: [0.7, 1.3], colors: ['rgba(170,205,255,0.95)', 'rgba(255,255,255,0.9)', 'rgba(130,170,255,0.9)'] }],
  'stars-dim': [500, { seed: 53, size: 500, count: 14, radius: [0.5, 0.9], colors: silver }],
  'dust-s': [520, { seed: 67, size: 520, count: 30, radius: [1.0, 2.0], colors: palette, soft: true }],
  'dust-m': [680, { seed: 71, size: 680, count: 18, radius: [2.0, 3.6], colors: palette, soft: true }],
  'dust-l': [880, { seed: 79, size: 880, count: 9, radius: [3.4, 6.0], colors: palette, soft: true }],
  'sparkle': [540, { seed: 83, size: 540, count: 20, radius: [0.8, 1.8], colors: pinks, soft: true }],
};

let css = '/* GENERATED by scripts/gen-cosmos-tiles.mjs: do not edit by hand. Original, seeded star and dust tiles. */\n:root {\n';
for (const [name, [size, def]] of Object.entries(tiles)) {
  css += `  --tile-${name}-size: ${size}px;\n  --tile-${name}: ${tile(def)};\n`;
}
css += '}\n';
writeFileSync(new URL('../src/cosmos-tiles.css', import.meta.url), css);
console.log(`wrote src/cosmos-tiles.css (${(css.length / 1024).toFixed(1)} KB, ${Object.keys(tiles).length} tiles)`);
